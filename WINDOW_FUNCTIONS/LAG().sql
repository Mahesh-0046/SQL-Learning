--CTE:
WITH CTE AS(
SELECT
	DEPARTMENT,
	SALE_DATE,
	SALES,
	
	LAG(SALES, 2, 0) OVER(ORDER BY SALE_DATE) AS PREVIOUS_SALES
FROM DEPARTMENT_SALES
)
SELECT 
	DEPARTMENT,
	SALE_DATE,
	SALES,
	PREVIOUS_SALES
FROM CTE
WHERE SALES > PREVIOUS_SALES;