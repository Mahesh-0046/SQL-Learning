--PREVIOUS SALES:
SELECT SALE_DATE, SALES,
LAG(SALES) OVER(ORDER BY SALE_DATE) AS PREVIOUS_DAY_SALES
FROM SALES;

--COMPARING CURRENT SALES - PREVIOUS SALES:
SELECT
	SALE_DATE,
	SALES,
	SALES - LAG(SALES) OVER (ORDER BY SALE_DATE) AS DIFFERENCE
FROM SALES;

--MONTH - OVER - MONTH GROWTH:
SELECT
	SALE_DATE,
	SALES,
	LAG(SALES) OVER(ORDER BY SALE_DATE) AS PREVIOUS_SALES,

	SALES - LAG(SALES) OVER(ORDER BY SALE_DATE) AS DIFFERENCE
FROM SALES;

--PERCENTAGE GROWTH:
SELECT
	SALE_DATE,
	SALES,
	ROUND(
		(
			SALES - LAG(SALES) OVER (
				ORDER BY
					SALE_DATE
			)
		) * 100.0 / LAG(SALES) OVER (
			ORDER BY
				SALE_DATE
		),
		2
	) AS GROWTH_PERCENT
FROM
	SALES;
	

