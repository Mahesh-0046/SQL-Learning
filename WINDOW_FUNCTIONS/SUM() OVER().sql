/*TOTAL PER DEPARTMENT — QUESTION 1

WRITE A QUERY TO DISPLAY: DEPARTMENT, SALE_DATE, SALES
TOTAL SALES FOR EACH DEPARTMENT ON EVERY ROW*/
SELECT 
	DEPARTMENT,
	SALE_DATE,
	SALES,

	SUM(SALES) OVER(PARTITION BY DEPARTMENT) AS DEPARTMENT_TOTAL
FROM DEPARTMENT_SALES;	

/*  WRITE A QUERY TO DISPLAY: ID, DEPARTMENT, SALE_DATE, SALES
TOTAL SALES FOR EACH DEPARTMENT
ORDER FINAL OUTPUT BY:
DEPARTMENT, SALE_DATE    */
WITH CTE AS(
SELECT
	ID,
	DEPARTMENT,
	SALE_DATE,
	SALES,

	SUM(SALES) OVER(PARTITION BY DEPARTMENT) AS DEPARTMENT_TOTAL
FROM DEPARTMENT_SALES	
)
SELECT
	ID,
	DEPARTMENT,
	SALE_DATE,
	SALES,
	DEPARTMENT_TOTAL
FROM CTE
ORDER BY DEPARTMENT, SALE_DATE;

/*CONTRIBUTION ANALYSIS — QUESTION 1

WRITE A QUERY TO DISPLAY: DEPARTMENT, SALE_DATE, SALES
PERCENTAGE CONTRIBUTION OF EACH ROW TO TOTAL SALES ACROSS THE ENTIRE 
TABLE*/
WITH CTE AS(
SELECT
	DEPARTMENT,
	SALE_DATE,
	SALES,
	SUM(SALES) OVER() AS TOTAL_SALES
FROM DEPARTMENT_SALES
)
SELECT
	DEPARTMENT,
	SALE_DATE,
	SALES,

	ROUND(
		SALES * 100.0
			/
			TOTAL_SALES, 2
	) AS PERCENTAGE_CONTRIBUTION
FROM CTE;

