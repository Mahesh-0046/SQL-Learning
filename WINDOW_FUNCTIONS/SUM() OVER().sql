/*RUNNING TOTALS QUESTION 1:

USING DEPARTMENT_SALES TABLE,
WRITE A QUERY TO DISPLAY:SALE_DATE, SALES, 
RUNNING TOTAL OF SALES BASED ON SALE_DATE */

WITH CTE AS(
SELECT 
	SALE_DATE,
	SALES,

	SUM(SALES) OVER(ORDER BY SALE_DATE) AS RUNNING_TOTALS

FROM DEPARTMENT_SALES
)
SELECT 
	SALE_DATE,
	SALES,
	RUNNING_TOTALS
FROM CTE;

/*RUNNING TOTALS QUESTION 2:
WRITE A QUERY TO DISPLAY:DEPARTMENT, SALE_DATE, SALES,
RUNNING TOTAL OF SALES SEPARATELY FOR EACH DEPARTMENT BASED ON SALE_DATE 
DO NOT COLLAPSE ROWS.*/

WITH CTE AS(
SELECT 
	DEPARTMENT,
	SALE_DATE,
	SALES,

	SUM(SALES) OVER(PARTITION BY DEPARTMENT ORDER BY SALE_DATE) AS RUNNING_TOTALS

FROM DEPARTMENT_SALES
)
SELECT 
	DEPARTMENT,
	SALE_DATE,
	SALES,
	RUNNING_TOTALS
FROM CTE;

